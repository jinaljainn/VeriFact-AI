
import sys
import hashlib
import tempfile
from pathlib import Path
from datetime import datetime

import streamlit as st

# -----------------------------------------
# PROJECT PATH
# -----------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJECT_ROOT))

from src.pdf_processing.uploaded_pdf_pipeline import (
    process_uploaded_pdf
)

from src.hallucination_detection.hallucination_detector import (
    detect_hallucination
)

from src.hallucination_detection.verdict_engine import (
    generate_final_verdict
)

from src.hallucination_detection.correction_engine import (
    generate_correction
)

from src.hallucination_detection.pdf_report_generator import (
    generate_pdf_report
)


# -----------------------------------------
# PAGE CONFIGURATION
# -----------------------------------------

st.set_page_config(
    page_title="VeriFact AI",
    page_icon="🔍",
    layout="wide"
)


# -----------------------------------------
# CUSTOM STYLING
# -----------------------------------------

st.markdown("""
<style>

.main-title {
    font-size: 42px;
    font-weight: bold;
    color: #2563EB;
    text-align: center;
}

.subtitle {
    font-size: 17px;
    color: #777777;
    text-align: center;
}

.section-title {
    font-size: 23px;
    font-weight: bold;
    margin-top: 20px;
}

</style>
""", unsafe_allow_html=True)


# -----------------------------------------
# APPLICATION HEADER
# -----------------------------------------

st.markdown(
    '<div class="main-title">🔍 VeriFact AI</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">'
    'LLM Hallucination Detection and Correction System'
    '</div>',
    unsafe_allow_html=True
)

st.divider()


# -----------------------------------------
# PROJECT INTRODUCTION
# -----------------------------------------

st.markdown("### Welcome to VeriFact AI")

st.write(
    """
    VeriFact AI is a reference-document-grounded system
    designed to identify potentially hallucinated claims
    generated by Large Language Models (LLMs).

    Upload a reference document and enter a claim.
    The system retrieves relevant evidence and evaluates
    whether the claim is supported by the document.
    """
)


# -----------------------------------------
# SESSION STATE INITIALIZATION
# -----------------------------------------

if "document_data" not in st.session_state:
    st.session_state.document_data = None

if "document_hash" not in st.session_state:
    st.session_state.document_hash = None

if "verification_result" not in st.session_state:
    st.session_state.verification_result = None

if "report_pdf_bytes" not in st.session_state:
    st.session_state.report_pdf_bytes = None


# -----------------------------------------
# DOCUMENT UPLOAD SECTION
# -----------------------------------------

st.markdown(
    '<div class="section-title">1. Upload Reference Document</div>',
    unsafe_allow_html=True
)

uploaded_file = st.file_uploader(
    "Upload your reference PDF",
    type=["pdf"]
)


# -----------------------------------------
# PROCESS UPLOADED PDF
# -----------------------------------------

if uploaded_file is not None:

    pdf_bytes = uploaded_file.getvalue()

    current_hash = hashlib.sha256(pdf_bytes).hexdigest()

    if current_hash != st.session_state.document_hash:

        st.session_state.document_data = None
        st.session_state.document_hash = None
        st.session_state.verification_result = None
        st.session_state.report_pdf_bytes = None

        try:

            with st.spinner(
                "Processing PDF... Extracting text, semantic pieces and embeddings."
            ):

                document_data = process_uploaded_pdf(pdf_bytes)

                st.session_state.document_data = document_data
                st.session_state.document_hash = current_hash

            st.success(
                f"Successfully processed: {uploaded_file.name}"
            )

        except Exception as error:

            st.error("PDF processing failed.")
            st.exception(error)

    if st.session_state.document_data is not None:

        document_data = st.session_state.document_data

        st.success(
            f"Document ready: {uploaded_file.name}"
        )

        col1, col2, col3 = st.columns(3)

        col1.metric(
            "Total Pages",
            document_data["total_pages"]
        )

        col2.metric(
            "Semantic Pieces",
            document_data["total_pieces"]
        )

        col3.metric(
            "Embeddings",
            len(document_data["embeddings"])
        )


# -----------------------------------------
# CLAIM INPUT SECTION
# -----------------------------------------

st.markdown(
    '<div class="section-title">2. Enter Claim to Verify</div>',
    unsafe_allow_html=True
)

claim = st.text_area(
    "Enter the statement generated by an LLM:",
    placeholder=(
        "Example: Correlation always means that "
        "one variable causes a change in another variable."
    ),
    height=120
)


# -----------------------------------------
# VERIFICATION BUTTON
# -----------------------------------------

if st.button(
    "🔍 Verify Claim",
    use_container_width=True
):

    if uploaded_file is None:

        st.warning("Please upload a reference PDF first.")

    elif st.session_state.document_data is None:

        st.warning("Please wait until PDF processing is completed.")

    elif not claim.strip():

        st.warning("Please enter a claim to verify.")

    else:

        try:

            document_data = st.session_state.document_data

            with st.spinner(
                "Retrieving evidence and verifying your claim..."
            ):

                # STEP 1: SEMANTIC RETRIEVAL AND NLI

                verification_results = detect_hallucination(
                    claim=claim.strip(),
                    top_k=5,
                    reference_embeddings=document_data["embeddings"]
                )

                # STEP 2: FINAL VERDICT

                final_result = generate_final_verdict(
                    claim.strip(),
                    verification_results
                )

                # STEP 3: CORRECTION

                correction_result = generate_correction(
                    claim.strip(),
                    final_result
                )

                st.session_state.verification_result = {
                    "claim": claim.strip(),
                    "reference_document": uploaded_file.name,
                    "verification_results": verification_results,
                    "final_result": final_result,
                    "correction_result": correction_result
                }

                # Clear any previous PDF report

                st.session_state.report_pdf_bytes = None

        except Exception as error:

            st.error("Claim verification failed.")
            st.exception(error)


# -----------------------------------------
# DISPLAY VERIFICATION RESULTS
# -----------------------------------------

result_data = st.session_state.verification_result

if result_data is not None:

    st.divider()

    st.markdown("## 3. Verification Results")

    st.markdown("**Original Claim:**")

    st.write(result_data["claim"])

    final_result = result_data["final_result"]

    verdict = final_result.get("verdict", "Unverified")

    # -------------------------------------
    # DISPLAY VERDICT
    # -------------------------------------

    if verdict == "Supported":

        st.success("Verdict: Supported")

    elif verdict == "Contradicted":

        st.error("Verdict: Contradicted")

    else:

        st.warning("Verdict: Unverified")

    st.markdown("**Explanation:**")

    st.write(
        final_result.get(
            "explanation",
            "No explanation available."
        )
    )


    # -------------------------------------
    # SUGGESTED CORRECTION
    # -------------------------------------

    st.markdown("### 4. Suggested Correction")

    correction_result = result_data["correction_result"]

    corrected_claim = correction_result.get("corrected_claim")
    correction_explanation = correction_result.get("explanation")
    source_page = correction_result.get("source_page")
    correction_source = correction_result.get("correction_source")

    if corrected_claim:

        if verdict == "Contradicted":

            st.success("A corrected statement is available.")

        elif verdict == "Supported":

            st.info("The original claim is already supported.")

        st.markdown("**Corrected Statement:**")

        st.markdown(
            f"""
            <div style="
                background-color: #E8F5E9;
                padding: 18px;
                border-radius: 10px;
                border-left: 5px solid #2E7D32;
                font-size: 17px;
            ">
                {corrected_claim}
            </div>
            """,
            unsafe_allow_html=True
        )

        if correction_source:

            st.write("**Source:**", correction_source)

        if source_page:

            st.write("**Source Page:**", source_page)

        if correction_explanation:

            st.write("**Explanation:**", correction_explanation)

    else:

        st.warning(
            "No correction could be generated because the available "
            "reference evidence is insufficient."
        )


    # -------------------------------------
    # RETRIEVED EVIDENCE
    # -------------------------------------

    st.markdown("### 5. Retrieved Evidence")

    verification_results = result_data["verification_results"]

    for item in verification_results:

        with st.expander(
            f"Reference {item['rank']} | Page {item['page_number']} | "
            f"{item['classification']}"
        ):

            st.write("**Reference Text:**")

            st.write(item["reference"])

            st.write(
                "**Similarity Score:**",
                item["similarity_score"]
            )

            st.write(
                "**NLI Classification:**",
                item["classification"]
            )

            st.write(
                "**NLI Confidence:**",
                str(item["confidence"]) + "%"
            )

            st.write("**Classification Scores:**")

            st.json(item["scores"])


    # -------------------------------------
    # PDF REPORT GENERATION
    # -------------------------------------

    st.divider()

    st.markdown("## 6. Download Verification Report")

    st.write(
        """
        Generate a detailed PDF report containing the original claim,
        final verdict, corrected statement, retrieved evidence and
        NLI verification results.
        """
    )

    if st.button(
        "📄 Generate PDF Report",
        use_container_width=True
    ):

        # -------------------------------------
        # GROUP EVIDENCE USING INDIVIDUAL NLI LABELS
        # -------------------------------------

        supporting_evidence = [
            item for item in verification_results
            if str(
                item.get(
                    "nli_classification",
                    item.get("classification", "")
                )
            ).strip().lower() == "entailment"
        ]

        contradicting_evidence = [
            item for item in verification_results
            if str(
                item.get(
                    "nli_classification",
                    item.get("classification", "")
                )
            ).strip().lower() == "contradiction"
        ]

        neutral_evidence = [
            item for item in verification_results
            if str(
                item.get(
                    "nli_classification",
                    item.get("classification", "")
                )
            ).strip().lower() == "neutral"
        ]

        # -------------------------------------
        # PREPARE EVIDENCE SUMMARY
        # -------------------------------------

        evidence_summary = {

            "supporting_evidence": supporting_evidence,

            "contradicting_evidence": contradicting_evidence,

            "neutral_evidence": neutral_evidence,

            "supporting_evidence_count": len(
                supporting_evidence
            ),

            "contradicting_evidence_count": len(
                contradicting_evidence
            ),

            "neutral_evidence_count": len(
                neutral_evidence
            ),

            "total_references_checked": len(
                verification_results
            )
        }

        # -------------------------------------
        # PREPARE COMPLETE REPORT
        # -------------------------------------

        report_data = {

            "project": "VeriFact AI",

            "report_generated_at": datetime.now().strftime(
                "%Y-%m-%d %H:%M:%S"
            ),

            "reference_document": result_data.get(
                "reference_document",
                "Uploaded reference document"
            ),

            "original_claim": result_data["claim"],

            "final_verdict": {
                "status": verdict,
                "explanation": final_result.get("explanation")
            },

            "correction": correction_result,

            "evidence_summary": evidence_summary,

            "all_verification_results": verification_results
        }

        temp_path = None

        try:

            with st.spinner("Generating your PDF report..."):

                # Create a temporary PDF file

                with tempfile.NamedTemporaryFile(
                    suffix=".pdf",
                    delete=False
                ) as temp_file:

                    temp_path = Path(temp_file.name)

                # Generate PDF using the report generator

                generate_pdf_report(
                    report=report_data,
                    output_path=temp_path
                )

                # Read generated PDF into memory

                pdf_bytes = temp_path.read_bytes()

                st.session_state.report_pdf_bytes = pdf_bytes

            st.success("Your verification report is ready!")

        except Exception as error:

            st.error("PDF report generation failed.")
            st.exception(error)

        finally:

            # Remove temporary file after reading

            if temp_path is not None and temp_path.exists():

                temp_path.unlink()


    # -------------------------------------
    # DOWNLOAD BUTTON
    # -------------------------------------

    if st.session_state.report_pdf_bytes is not None:

        st.download_button(
            label="⬇️ Download Verification Report",
            data=st.session_state.report_pdf_bytes,
            file_name="VeriFact_AI_Verification_Report.pdf",
            mime="application/pdf",
            use_container_width=True
        )


# -----------------------------------------
# FOOTER
# -----------------------------------------

st.divider()

st.markdown(
    "<center>VeriFact AI | Academic Mini Project</center>",
    unsafe_allow_html=True
)
